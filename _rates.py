def residual_rate(age: int, origin: str = "국산") -> float:
    """경과연수별 잔가율. age=0 은 '1년 미만'."""
    table = RESIDUAL_PUBLISHED.get(origin, RESIDUAL_PUBLISHED["국산"])
    if age in table:
        return table[age]
    last = max(table)
    rate = table[last] * (RESIDUAL_DECAY[origin] ** (min(age, RESIDUAL_MAX_AGE) - last))
    return max(round(rate, 4), RESIDUAL_FLOOR)


