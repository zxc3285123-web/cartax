def slug(maker: str, name: str) -> str:
    import re
    base = f"{maker}-{name}".lower().replace(" ", "-")
    base = re.sub(r"[^0-9a-z가-힣\-]", "", base)
    return re.sub(r"-+", "-", base).strip("-")
